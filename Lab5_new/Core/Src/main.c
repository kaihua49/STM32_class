	        uint32_t max_arr = __HAL_TIM_GET_AUTORELOAD(&htim3);

	        /* 計算每 10ms 需遞增/遞減的步進量（1秒內需更新 100 次，故除以 100） */
	        uint32_t step = max_arr / 100;

