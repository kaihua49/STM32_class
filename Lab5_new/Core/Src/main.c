    __HAL_TIM_SET_PRESCALER(&htim3, 16);
  /* 啟動 TIM3 通道 3 的 PWM 輸出 (對應 PC8) */
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_3);
  /* 啟動 TIM3 通道 4 的 PWM 輸出 (對應 PC9) */
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_4);
